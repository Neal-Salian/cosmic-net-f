#!/usr/bin/env python3
"""Export five booktabs LaTeX tables from the verified numerical analysis."""
import json
from analyze_results import PAPER, LABELS, METHODS, verify_inputs, sha

OUT = PAPER / "tables"


def label(method):
    return LABELS[method].replace("×", r"$\times$")


def table(name, number, caption, headings, rows, note, wide=False, alignment=None):
    env = "table*" if wide else "table"
    alignment = alignment or ("l" + "r"*(len(headings)-1))
    text = ["% Generated by paper/scripts/generate_tables.py. Requires booktabs.",
            rf"\begin{{{env}}}[t]", r"\centering", r"\small",
            rf"\caption{{{caption}}}", rf"\label{{tab:cosmic-{number}}}",
            r"\setlength{\tabcolsep}{4pt}", rf"\begin{{tabular}}{{{alignment}}}", r"\toprule",
            " & ".join(headings) + r" \\", r"\midrule"]
    text.extend(" & ".join(str(x) for x in row) + r" \\" for row in rows)
    text.extend([r"\bottomrule", r"\end{tabular}", r"\par\smallskip",
                 rf"\begin{{minipage}}{{{'0.98\\textwidth' if wide else '0.98\\columnwidth'}}}",
                 r"\footnotesize " + note, r"\end{minipage}", rf"\end{{{env}}}", ""])
    (OUT / f"table_{number}_{name}.tex").write_text("\n".join(text))


def pvalue(p):
    return "---" if p is None else (f"{p:.5f}" if p < .001 else f"{p:.4f}")


def main():
    verify_inputs()
    d = json.loads((PAPER / "evidence/analysis.json").read_text())
    if d["analysis_script_sha256"] != sha((PAPER/"scripts/analyze_results.py").read_bytes()) or \
       d["input_manifest_sha256"] != sha((PAPER/"evidence/inputs/manifest.json").read_bytes()):
        raise ValueError("Analysis is stale; rerun generate_figures.py first")
    OUT.mkdir(parents=True, exist_ok=True)
    s = d["setup"]
    table("dataset_setup", 1, "Dataset and experimental setup for the legacy A--D campaign.",
          ["Property", "Value"], [
              ["Catalog / scope", r"TNG100; legacy\_total\_radius"],
              ["Catalog rows / halo graphs", f"{s['catalog_rows']:,} / {s['halos']}"],
              ["Train / validation / test halos", "378 / 81 / 82"],
              ["Node / edge features", "4 / 5"],
              ["Radius graph / architecture loops", "2.0 Mpc / retained"],
              ["Test physical pairs (min / median / max)", "15 / 45 / 45"],
              ["C nominal retention", r"40\%, 60\%, 80\%, 100\%"],
              ["D nominal retention", r"50\%"],
              ["Experiment seed / fitted policy seeds", "42 / 1"],
              ["Selected policy epoch (zero based)", str(s["policy_selected_epoch"])],
              ["Optional Stage B training cohort", "377 / 378 (topology preflight)"],
              ["Bootstrap / permutation draws", "50,000 / 99,999"],
              ["Analysis seed", str(d["seed"])],
              ["Execution device / graph backend", r"CUDA / portable\_torch"],
          ], r"Split IDs and input identities agree across A--D. Budget $B_i=\lceil qP_i\rceil$ counts distinct non-self physical pairs. Self-loops and both orientations are retained. The legacy target and radius semantics, backbone training provenance, and independent-volume generalization remain uncertified.",
          wide=True, alignment="ll")
    rows = []
    for method in ["full"] + METHODS:
        ms = [next(x for x in d["metrics"] if x["q"] == q and x["method"] == method)
              for q in [.4, .6, .8, 1.]]
        rows.append([label(method)] + [f"{x['rmse']:.6f}" for x in ms] +
                    [f"{ms[0]['mae']:.6f}", f"{ms[0]['r2']:.6f}"])
    physical = [next(x for x in d["metrics"] if x["q"] == q and x["method"] == "provided_rl")
                for q in [.4, .6, .8, 1.]]
    table("primary_benchmark", 2, "Primary frozen-backbone matched-budget test benchmark (82 halos).",
          ["Method", r"$q=.4$", r"$q=.6$", r"$q=.8$", r"$q=1$", r"MAE ($q=.4$)", r"$R^2$ ($q=.4$)"], rows,
          "RMSE and MAE are in dex. Mean realized physical retention for pruned methods is " +
          ", ".join(f"{100*x['physical_retention']:.2f}\\%" for x in physical) +
          r", respectively. Every method has identical per-halo budgets at each $q$. Full graph is a 100\% reference in every column. Point estimates describe one fitted model and one random test-mask realization; no training-seed error bars are available.", wide=True)
    rows = []
    order = ["edge_feature_grad_x_input", "random", "supervised_raw", "degree", "distance", "stellar_binding_proxy", "full"]
    for q in [.4, .6, .8]:
        for method in order:
            x = next(x for x in d["contrasts"] if x["q"] == q and x["control"] == method)
            rows.append([f"{q:.1f}", label(method) + (r"$^\dagger$" if method == "full" else ""),
                         f"{x['delta_rmse']:+.6f}", f"[{x['ci_low']:+.6f}, {x['ci_high']:+.6f}]",
                         pvalue(x["p"]), pvalue(x["holm7"]), pvalue(x["holm21"])])
    table("statistical_comparisons", 3, "Exploratory paired RL comparisons on 82 test halos.",
          [r"$q$", "Control", r"$\Delta$RMSE (dex)", r"95\% BCa CI (dex)", r"$p$", r"Holm$_7$", r"Holm$_{21}$"], rows,
          r"Negative differences favor RL. CIs use 50,000 paired halo bootstrap draws and are unadjusted pointwise intervals, not simultaneous intervals. Two-sided $p$ values use 99,999 within-halo swaps of squared errors (MSE statistic). Holm$_7$ corrects the seven $q=.4$ controls; Holm$_{21}$ corrects all 21 rows. Dashes mean outside that family. $^\dagger$Full graph retains 100\% and is a reference, not a matched-budget control. All tests are post hoc; none constitutes confirmatory evidence.", wide=True, alignment="rllrrrr")
    rows = []
    full = next(x for x in d["metrics"] if x["q"] == .4 and x["method"] == "full")
    for method in ["full"] + METHODS:
        x = next(x for x in d["metrics"] if x["q"] == .4 and x["method"] == method)
        rows.append([label(method), f"{x['scoring_s']:.6f}", f"{x['decoder_s']:.6f}",
                     f"{x['prediction_s']+x['full_s']:.6f}", f"{x['latency_s']:.6f}",
                     f"{x['latency_s']/full['latency_s']:.2f}", f"{x['live_forward_calls']:.0f}"])
    table("runtime", 4, r"Measured C inference regions at nominal 40\% physical-pair retention.",
          ["Method", "Scoring", "Decoding", "Prediction", "Total", r"Time / full", "GNN calls"], rows,
          r"Times are mean seconds per halo from one saved execution per halo; no repeated-run timing CIs are available. Scoring includes embedding extraction and policy/saliency work; total includes region overhead and need not equal the three components. Full reference retains 100\%. Graph construction (0.851806 s for the split set), setup, ingestion and historical training are excluded. GNN calls are measured live predictor forwards per halo. RL historical training time and exact accelerator model were not recorded.", wide=True)
    base = d["adaptation"][0]
    rows = []
    for x in d["adaptation"]:
        rows.append([str(x["K"]) + (r"$^*$" if x["selected"] else ""),
                     f"{x['val_rmse']:.9f}", f"{x['rmse']:.9f}", f"{x['mae']:.9f}",
                     f"{x['latency_s']:.6f}", f"{x['latency_s']/base['latency_s']:.3f}", f"{x['steps']:.3f}"])
    table("adaptation", 5, r"D test-time adaptation at nominal 50\% retention (82 test halos).",
          [r"$K$", "Val. RMSE", "Test RMSE", "Test MAE", "s/halo", r"Time / $K=0$", "Actual steps"], rows,
          r"RMSE/MAE are in dex; extra digits preserve the very small validation selection gap. $^*$Selected on validation only. Mean realized physical-pair retention is 51.01\%; stored-column retention including loops is 56.25\%. Final per-halo budgets are identical across $K$. Early stopping limits actual steps. Only aggregate final accuracy was saved; no paired accuracy tests or accuracy error bars can be recovered. D's 50\% budget is separate from C's 40\% benchmark.", wide=True)
    rl = next(x for x in d["metrics"] if x["q"] == .4 and x["method"] == "provided_rl")
    grad = next(x for x in d["contrasts"] if x["q"] == .4 and x["control"] == "edge_feature_grad_x_input")
    rnd = next(x for x in d["contrasts"] if x["q"] == .4 and x["control"] == "random")
    selected = next(x for x in d["adaptation"] if x["selected"])
    results = rf"""% Generated from verified evidence; exploratory results, not a confirmatory claim.
On the common test split of 82 halos, the frozen full-graph reference attained
an RMSE of {full['rmse']:.6f} dex. At nominal 40\% physical-pair retention
(mean realized retention {100*rl['physical_retention']:.2f}\%), RL attained
{rl['rmse']:.6f} dex, compared with 0.136900 dex for gradient $\times$ input,
0.147382 dex for the trained selector, and 0.156571 dex for random selection.
RL's RMSE was {100*(rl['rmse']/full['rmse']-1):.2f}\% higher than the full reference.

The exploratory paired RL-minus-gradient RMSE difference was
{grad['delta_rmse']:+.6f} dex (unadjusted 95\% BCa CI
[{grad['ci_low']:+.6f}, {grad['ci_high']:+.6f}]; two-sided paired MSE permutation
$p={grad['p']:.4f}$; Holm-adjusted $p={grad['holm7']:.4f}$ for seven comparisons).
The RL-minus-random difference was {rnd['delta_rmse']:+.6f} dex
(95\% CI [{rnd['ci_low']:+.6f}, {rnd['ci_high']:+.6f}]; $p={rnd['p']:.4f}$;
Holm-adjusted $p={rnd['holm7']:.4f}$). Neither comparison establishes an accuracy
advantage. Intervals are conditional on one fitted policy, backbone and legacy
split, and do not capture training-seed or simulation-volume uncertainty.

Mean measured inference time at nominal 40\% retention was
{rl['latency_s']:.6f} s per halo for RL and {full['latency_s']:.6f} s for the full
reference, a {rl['latency_s']/full['latency_s']:.2f}-fold slowdown. Graph construction,
setup and historical training are outside these measured inference regions.

At the separate nominal 50\% adaptation budget, validation selected $K=20$.
Test RMSE changed from {base['rmse']:.9f} to {selected['rmse']:.9f} dex
({100*(1-selected['rmse']/base['rmse']):.3f}\% improvement), while mean latency increased
{selected['latency_s']/base['latency_s']:.3f}-fold. No final per-halo adaptation
predictions were saved, so this accuracy change is descriptive and has no
recoverable paired confidence interval or significance test.
"""
    (PAPER / "results.tex").write_text(results)
    print("Exported five LaTeX tables:", OUT)


if __name__ == "__main__":
    main()
